interface PixelLedDisplayProps {
  text?: string;
  ledColor?: string;
  dimColor?: string;
  pixelSize?: number;
  gap?: number;
  speed?: number;
  marquee?: boolean;
  className?: string;
}

export default function PixelLedDisplay({
  text = "ZENUXS PLATFORM • 10/10 SYSTEMS ONLINE • RFC 7636 READY",
  ledColor = "#10b981",
  dimColor = "#141a16",
  pixelSize = 3.5,
  gap = 1.5,
  speed = 40,
  marquee = true,
  className = "",
}: PixelLedDisplayProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const containerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    let animId: number;
    let offset = 0;
    const upperText = (text + "   ").toUpperCase();

    // Convert string to 2D column array
    const columns: number[] = [];
    for (let i = 0; i < upperText.length; i++) {
      const char = upperText[i];
      const charData = FONT_5X7[char] || FONT_5X7[" "] || [0, 0, 0, 0, 0];
      columns.push(...charData, 0); // Add 1 column gap between characters
    }

    const totalCols = columns.length;
    const rows = 7;
    const colStep = pixelSize + gap;
    const rowStep = pixelSize + gap;

    const render = () => {
      const width = canvas.width;
      const height = canvas.height;
      ctx.clearRect(0, 0, width, height);

      const visibleCols = Math.ceil(width / colStep);

      for (let c = 0; c < visibleCols; c++) {
        const colIdx = marquee ? Math.floor((c + offset) % totalCols) : c;
        const colByte = colIdx < totalCols ? columns[colIdx] : 0;

        for (let r = 0; r < rows; r++) {
          const isLit = Boolean((colByte >> r) & 1);
          const x = c * colStep + pixelSize / 2;
          const y = r * rowStep + pixelSize / 2 + (height - rows * rowStep) / 2;

          ctx.beginPath();
          ctx.arc(x, y, pixelSize / 2, 0, Math.PI * 2);

          if (isLit) {
            ctx.fillStyle = ledColor;
            ctx.shadowColor = ledColor;
            ctx.shadowBlur = 6;
          } else {
            ctx.fillStyle = dimColor;
            ctx.shadowBlur = 0;
          }
          ctx.fill();
        }
      }

      if (marquee) {
        offset += speed * 0.02;
        if (offset >= totalCols) offset = 0;
      }

      animId = requestAnimationFrame(render);
    };

    const handleResize = () => {
      if (!containerRef.current || !canvas) return;
      canvas.width = containerRef.current.clientWidth;
      canvas.height = 42;
    };

    handleResize();
    window.addEventListener("resize", handleResize);
    render();

    return () => {
      window.removeEventListener("resize", handleResize);
      cancelAnimationFrame(animId);
    };
  }, [text, ledColor, dimColor, pixelSize, gap, speed, marquee]);

  return (
    <div
      ref={containerRef}
      className={`w-full overflow-hidden rounded-lg bg-black border border-border/80 p-2 shadow-inner ${className}`}
    >
      <canvas ref={canvasRef} className="block w-full h-[42px]" />
    </div>
  );
}
